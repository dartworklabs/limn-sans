"""Data for punct.html: the punctuation metrics of tools/punct.py for the brand drawing (the build of
limn-font.js: curve A, 700, Quicksand Bold S 120) and the reference fonts' own glyphs. The page measures
limn and the references from these outlines itself.

  uv run --no-project --with skia-pathops --with fonttools --with uharfbuzz python3 tools/build_punct_page.py

Reference TTFs (all SIL OFL) are read from LIMN_REF_DIRS (colon separated).
"""
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

import pathops
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "punct-data.js"
DIRS = [Path(p) for p in os.environ.get("LIMN_REF_DIRS", str(HERE.parent / "refs")).split(":")]   # make refs
REFS = [  # name, file, location, credit
    ("Quicksand", "Quicksand.ttf", {"wght": 700}, "Quicksand Bold (부모)"),
    ("Nunito", "Nunito.ttf", {"wght": 700}, "Nunito 700"),
    ("Varela Round", "VarelaRound.ttf", None, "Varela Round"),
    ("Comfortaa", "Comfortaa.ttf", {"wght": 700}, "Comfortaa 700"),
    ("Fredoka", "Fredoka.ttf", {"wght": 600, "wdth": 100}, "Fredoka 600"),
    ("M PLUS Rounded 1c", "MPLUSRounded1c-Bold.ttf", None, "M PLUS Rounded 1c Bold"),
    ("Baloo 2", "Baloo2[wght].ttf", {"wght": 700}, "Baloo 2 700"),
]
SET = ".,:;!?'\"()[]{}-–—_/\\|@#$%&*+=<>^~`·…¡¿‘’“”‚„×÷"
HEADER = (
    "/* limn punctuation data, generated by tools/build_punct_page.py, do not edit.\n"
    " * limn glyphs are a Modified Version of Quicksand (SIL Open Font License 1.1, see OFL.txt).\n"
    " * Reference outlines for comparison only, each under the SIL Open Font License 1.1 -\n"
    " *   Quicksand (The Quicksand Project Authors), Nunito (The Nunito Project Authors),\n"
    " *   Varela Round (Joe Prince), Comfortaa (Johan Aakerlund), Fredoka (The Fredoka Project Authors),\n"
    " *   M PLUS Rounded 1c (M+ FONTS PROJECT), Baloo 2 (Ek Type)\n"
    " */\n"
)
assert "=" not in HEADER and ";" not in HEADER


def d_of(p, k=1.0):
    pen = SVGPathPen(None, ntos=lambda v: ("%.1f" % v).rstrip("0").rstrip("."))
    p.draw(TransformPen(pen, (1, 0, 0, -1, 0, 0)))
    return pen.getCommands()


def ref_font(name, fn, loc):
    f = next(d / fn for d in DIRS if (d / fn).exists())
    t = TTFont(str(f))
    if loc: t = instantiateVariableFont(t, loc)
    gs = t.getGlyphSet(); cm = t.getBestCmap(); k = 1000 / t["head"].unitsPerEm; hm = t["hmtx"].metrics

    def path(ch):
        p = pathops.Path()
        gs[cm[ord(ch)]].draw(TransformPen(p.getPen(glyphSet=gs), (k, 0, 0, k, 0, 0)))
        p.simplify()
        return p
    b = lambda ch: path(ch).bounds
    glyphs = {ch: {"d": d_of(path(ch)), "adv": round(hm[cm[ord(ch)]][0] * k)} for ch in SET + " abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789" if ord(ch) in cm}
    return {"xh": round(b("x")[3]), "cap": round(b("H")[3]), "asc": round(b("l")[3]), "desc": round(b("p")[1]), "glyphs": glyphs}


# the metrics of punct.py, dumped by one build run of the brand drawing (as make font builds limn-font.js)
with tempfile.TemporaryDirectory() as tmp:
    dump = Path(tmp) / "punct.json"; play = Path(tmp) / "play.json"
    subprocess.run([sys.executable, str(HERE / "build_font.py")], check=True, stdout=subprocess.DEVNULL,
                   env={**os.environ, "LIMN_WCURVE": "A", "LIMN_WGHT": "700", "LIMN_PUNCT_DUMP": str(dump), "LIMN_PLAY_OUT": str(play)})
    dumped = json.loads(dump.read_text())

data = {"m": dumped["m"], "opt": dumped["opt"], "refs": {n: {**ref_font(n, fn, loc), "credit": c} for n, fn, loc, c in REFS}}
OUT.write_text(HEADER + "window.LIMN_PUNCT=" + json.dumps(data, ensure_ascii=True, separators=(",", ":")) + ";\n")
print("wrote", OUT, OUT.stat().st_size, "bytes")
